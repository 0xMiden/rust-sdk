    #[test]
    fn auth_args_set_the_commitment_and_its_preimage() {
        let auth_args = MultisigAuthArgs::new(BlockNumber::from(7u32), Word::from([1u32, 2, 3, 4]));

        let request = TransactionRequestBuilder::new()
            .fee_conversion_salt(Word::from([5u32, 6, 7, 8]))
            .auth_args(&auth_args)
            .build()
            .unwrap();

        let auth_arg = auth_args.to_commitment();
        assert_eq!(request.auth_arg(), &Some(auth_arg));
        assert_eq!(request.fee_conversion_salt(), None);
        assert_eq!(request.advice_map().get(&auth_arg).unwrap().as_ref(), auth_args.to_elements());
    }

    #[test]
    fn expiration_delta_without_script_template_builds_expiration_script() {
        let account = AccountBuilder::new(Default::default())
            .with_component(MockAccountComponent::with_empty_slots())
            .with_component(AuthSingleSig::new(Approver::new(
                PublicKeyCommitment::from(EMPTY_WORD),
                AuthScheme::Falcon512Poseidon2,
            )))
            .account_type(AccountType::Private)
            .build_existing()
            .unwrap();
        let code_interface = account.code_interface();

        let delta = NonZeroU16::new(9).unwrap();
        let tx_request =
            TransactionRequestBuilder::new().expiration_delta(delta.get()).build().unwrap();

        let (script, script_args) =
            tx_request.build_transaction_script(&code_interface).unwrap().unwrap();
        let expected = ExpirationTransactionScript::new(delta);
        assert_eq!(script.root(), TransactionScript::from(expected).root());
        assert_eq!(script_args, Some(expected.tx_script_args()));

        // Without a delta there is still no script to run.
        let tx_request = TransactionRequestBuilder::new().build().unwrap();
        assert!(tx_request.build_transaction_script(&code_interface).unwrap().is_none());
    }

    #[test]
    fn expected_output_recipients_keep_own_output_note_recipients() {
        let mut rng = ChaCha20Rng::seed_from_u64(0);
        let faucet_id = AccountId::try_from(ACCOUNT_ID_PRIVATE_FUNGIBLE_FAUCET).unwrap();
        let note: Note = P2idNote::builder()
            .sender(AccountId::try_from(ACCOUNT_ID_SENDER).unwrap())
            .target(AccountId::try_from(ACCOUNT_ID_REGULAR_PUBLIC_ACCOUNT_IMMUTABLE_CODE).unwrap())
            .assets(vec![FungibleAsset::new(faucet_id, 100).unwrap()])
            .note_type(NoteType::Private)
            .serial_number(rng.random())
            .build()
            .unwrap()
            .into();
        let recipient = note.recipient();
        let other = NoteRecipient::new(
            rng.random(),
            recipient.script().clone(),
            recipient.storage().clone(),
        );

        let tx_request = TransactionRequestBuilder::new()
            .own_output_notes([note.clone()])
            .expected_output_recipients([other])
            .build()
            .unwrap();

        assert_eq!(tx_request.expected_output_own_notes(), [note]);
        assert_eq!(tx_request.expected_output_recipients().count(), 2);
    }
