// Errors related to a [TransactionRequest]
#[derive(Debug, Error)]
pub enum TransactionRequestError {
    #[error("failed to build the send-notes transaction script")]
    SendNotesTransactionScriptError(#[from] SendNotesTransactionScriptError),
    #[error("account error")]
    AccountError(#[from] AccountError),
    #[error("asset error")]
    AssetError(#[from] AssetError),
    #[error("duplicate input note: note {0} was added more than once to the transaction")]
    DuplicateInputNote(NoteId),
    #[error("transaction expiration delta must be greater than zero")]
    ZeroExpirationDelta,
    #[error(
        "the account proof does not contain the required foreign account data; re-fetch the proof and retry"
    )]
    ForeignAccountDataMissing,
    #[error(
        "foreign account {0} has incompatible visibility; use `ForeignAccount::public()` for public accounts and `ForeignAccount::private()` for private accounts"
    )]
    InvalidForeignAccountId(AccountId),
    #[error(
        "inputs for foreign account {account_id} do not open against the account tree of the \
         transaction's reference block {block_num}"
    )]
    ForeignAccountNotAtReferenceBlock {
        account_id: AccountId,
        block_num: BlockNumber,
    },
    #[error(
        "note {0} cannot be used as an authenticated input: it does not have a valid inclusion proof"
    )]
    InputNoteNotAuthenticated(NoteId),
    #[error("note with details commitment {} has already been consumed", .0.to_hex())]
    InputNoteAlreadyConsumed(NoteDetailsCommitment),
    #[error(
        "note with details commitment {} is being consumed by pending transaction {transaction_id}",
        note.to_hex()
    )]
    InputNoteBeingProcessed {
        note: NoteDetailsCommitment,
        transaction_id: TransactionId,
    },
    #[error(
        "output note declares sender {actual} but the transaction is executed by account {expected}"
    )]
    OutputNoteSenderMismatch { expected: AccountId, actual: AccountId },
    #[error(
        "the request declares a fee conversion salt but the account's auth component {0} does not \
         read the auth args as fee conversion info"
    )]
    FeeConversionInfoUnsupported(String),
    #[error(
        "account's `{0}` component reuses the fee conversion salt as a replay guard, so the \
         caller must declare a fresh one with `TransactionRequestBuilder::fee_conversion_salt`"
    )]
    FeeConversionInfoRequired(String),
    #[error("merkle proof error")]
    MerkleError(#[from] MerkleError),
    #[error("empty transaction: the request has no input notes and no account state changes")]
    NoInputNotesNorAccountChange,
    #[error("failed to create note")]
    NoteCreationError(#[from] NoteError),
    #[error("note failed validation")]
    NoteValidationError(#[source] NoteError),
    #[error("note execution failed")]
    NoteExecutionError(#[source] NoteError),
    #[error("failed to build note args")]
    NoteArgError(#[source] NoteError),
    #[error("pay-to-ID note must contain at least one asset to transfer")]
    P2IDNoteWithoutAsset,
    #[error("swap note assets must be non-zero: a zero {0} asset makes the exchange one-sided")]
    SwapNoteWithZeroAsset(&'static str),
    #[error(
        "non-fungible asset issued by faucet {0} is not available in the account vault or incoming notes"
    )]
    MissingNonFungibleAsset(AccountId),
    #[error("PSWAP note can only be cancelled by its creator: expected {expected}, got {actual}")]
    PswapCancelCreatorMismatch { expected: AccountId, actual: AccountId },
    #[error("error building script")]
    CodeBuilderError(#[from] CodeBuilderError),
    #[error("transaction script template error: {0}")]
    ScriptTemplateError(String),
    #[error("foreign procedure takes at most {max} input felts, got {actual}")]
    ForeignProcedureInputsTooLong { max: usize, actual: usize },
    #[error("storage slot {0} not found in account ID {1}")]
    StorageSlotNotFound(u8, AccountId),
    #[error("error while building the input notes")]
    TransactionInputError(#[from] TransactionInputError),
    #[error("account storage map error")]
    StorageMapError(#[from] StorageMapError),
}

