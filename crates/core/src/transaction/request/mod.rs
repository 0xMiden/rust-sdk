pub type NoteArgs = Word;

/// Specifies the transaction script of a [`TransactionRequest`].
///
/// A transaction script is a program which is executed after scripts of all input notes have been
/// executed.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RequestScript {
    /// The executing client generates the script. The script creates `own_output_notes` and expires
    /// the transaction after `expiration_delta` blocks if it is set. At least one of them is set.
    ///
    /// The generated script depends on the capabilities of the executing account. For example, for
    /// Basic Wallets, this may involve invoking `create_note` procedure.
    Generated {
        own_output_notes: Vec<Note>,
        expiration_delta: Option<NonZeroU16>,
    },
    /// The exact script to execute, and the word that the script receives as its `TX_SCRIPT_ARGS`.
    /// `None` gives the script an empty word.
    Custom {
        script: TransactionScript,
        arg: Option<Word>,
    },
}

/// An input note of a [`TransactionRequest`], with its arguments.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RequestInputNote {
    authentication: InputNoteAuthentication,
    args: Option<NoteArgs>,
}

impl RequestInputNote {
    /// Returns how the note is authenticated when it is consumed.
    pub fn authentication(&self) -> &InputNoteAuthentication {
        &self.authentication
    }

    /// Returns the note.
    pub fn note(&self) -> &Note {
        match &self.authentication {
            InputNoteAuthentication::Inferred(note) => note,
            InputNoteAuthentication::Explicit(input_note) => input_note.note(),
        }
    }

    /// Returns the ID of the note.
    pub fn id(&self) -> NoteId {
        self.note().id()
    }

    /// Returns the arguments of the note, or `None` if the note has no arguments.
    pub fn args(&self) -> Option<NoteArgs> {
        self.args
    }
}

/// Specifies whether a [`RequestInputNote`] is consumed as authenticated or as unauthenticated.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum InputNoteAuthentication {
    /// The executing client consumes the note as authenticated when its store holds the note's
    /// inclusion proof, and as unauthenticated otherwise.
    Inferred(Note),
    /// Every client consumes the note in the mode that the [`InputNote`] carries.
    Explicit(InputNote),
}

/// Specifies the auth args that the executing client passes to the auth procedure of the account.
///
/// The auth procedure receives the commitment of the auth args, and loads their preimage from the
/// advice map.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub enum RequestAuthArgs {
    /// The executing client builds the default auth args with its fixed default salt.
    #[default]
    Default,
    /// The executing client builds the default auth args with this salt.
    DefaultWithSalt(Word),
    /// The caller sets the auth args. The executing client does not change them.
    Explicit { commitment: Word, preimage: Vec<Felt> },
}

/// Specifies a transaction request that can be executed by an account.
///
/// A request contains information about input notes to be consumed by the transaction (if any),
/// blocks that must be available to the transaction, the transaction script to execute (if any),
/// and notes expected to be generated by this transaction or a later transaction.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TransactionRequest {
    /// Blocks that the transaction must be able to authenticate against its reference block.
    block_numbers: BTreeSet<BlockNumber>,
    /// Notes to be consumed by the transaction, in consumption order.
    input_notes: Vec<RequestInputNote>,
    /// Transaction script to execute, or `None` to run no transaction script.
    transaction_script: Option<RequestScript>,
    /// Recipients of the output notes that a custom script or the scripts of the input notes are
    /// expected to create, keyed by recipient digest.
    expected_output_recipients: BTreeMap<Word, NoteRecipient>,
    /// A map of details and tags of notes we expect to be created as part of future transactions
    /// with their respective tags.
    ///
    /// For example, after a swap note is consumed, a payback note is expected to be created.
    expected_future_notes: BTreeMap<NoteDetailsCommitment, (NoteDetails, NoteTag)>,
    /// Initial state of the `AdviceMap` that provides data during runtime.
    advice_map: AdviceMap,
    /// Initial state of the `MerkleStore` that provides data during runtime.
    merkle_store: MerkleStore,
    /// Foreign account data requirements keyed by account ID. At execution time, account data will
    /// be retrieved from the network, and injected as advice inputs. Additionally, the account's
    /// code will be added to the executor and prover.
    foreign_accounts: BTreeMap<AccountId, ForeignAccount>,
    /// Indicates whether to **silently** ignore invalid input notes when executing the transaction.
    /// This will allow the transaction to be executed even if some input notes are invalid.
    ignore_invalid_input_notes: bool,
    /// Auth args that the executing client passes to the auth procedure of the account.
    auth_args: RequestAuthArgs,
    /// Note scripts that the node's NTX builder will need in its script registry.
    ///
    /// See [`TransactionRequestBuilder::expected_ntx_scripts`] for details.
    expected_ntx_scripts: Vec<NoteScript>,
    /// New code of the executing account, set through
    /// [`TransactionRequestBuilder::account_code_upgrade`].
    account_code_upgrade: Option<AccountCodeUpgrade>,
}

impl TransactionRequest {
    // PUBLIC ACCESSORS
    // --------------------------------------------------------------------------------------------

    /// Returns the blocks that the transaction must be able to authenticate.
    pub fn block_numbers(&self) -> &BTreeSet<BlockNumber> {
        &self.block_numbers
    }

    /// Returns the input notes of the transaction request, in consumption order.
    pub fn input_notes(&self) -> &[RequestInputNote] {
        &self.input_notes
    }

    /// Returns the IDs of all input notes, in consumption order.
    pub fn input_note_ids(&self) -> impl Iterator<Item = NoteId> {
        self.input_notes.iter().map(RequestInputNote::id)
    }

    /// Returns the assets held by the transaction's input notes.
    pub fn incoming_assets(&self) -> (BTreeMap<AccountId, u64>, Vec<Asset>) {
        collect_assets(
            self.input_notes.iter().flat_map(|input_note| input_note.note().assets().iter()),
        )
    }

    /// Returns the number of blocks after the reference block at which the transaction expires, or
    /// `None` if the transaction does not expire.
    pub fn expiration_delta(&self) -> Option<u16> {
        match &self.transaction_script {
            Some(RequestScript::Generated { expiration_delta, .. }) => {
                expiration_delta.map(NonZeroU16::get)
            },
            _ => None,
        }
    }

    /// Returns the expected output own notes of the transaction.
    ///
    /// In this context "own notes" refers to notes that are expected to be created directly by the
    /// transaction script, rather than notes that are created as a result of consuming other notes.
    pub fn expected_output_own_notes(&self) -> Vec<Note> {
        match &self.transaction_script {
            Some(RequestScript::Generated { own_output_notes, .. }) => own_output_notes.clone(),
            _ => vec![],
        }
    }

    /// Returns an iterator over the recipients of the notes that a custom script or the scripts of
    /// the input notes are expected to create. The recipients of the own output notes are not
    /// included.
    pub fn expected_output_recipients(&self) -> impl Iterator<Item = &NoteRecipient> {
        self.expected_output_recipients.values()
    }

    /// Returns an iterator over expected future notes.
    pub fn expected_future_notes(&self) -> impl Iterator<Item = &(NoteDetails, NoteTag)> {
        self.expected_future_notes.values()
    }

    /// Returns the [`RequestScript`], or `None` if the transaction runs no transaction script.
    pub fn transaction_script(&self) -> &Option<RequestScript> {
        &self.transaction_script
    }

    /// Returns the [`AdviceMap`] for the transaction request.
    pub fn advice_map(&self) -> &AdviceMap {
        &self.advice_map
    }

    /// Returns a mutable reference to the [`AdviceMap`] for the transaction request.
    pub fn advice_map_mut(&mut self) -> &mut AdviceMap {
        &mut self.advice_map
    }

    /// Returns the [`MerkleStore`] for the transaction request.
    pub fn merkle_store(&self) -> &MerkleStore {
        &self.merkle_store
    }

    /// Returns the required foreign accounts keyed by account ID.
    pub fn foreign_accounts(&self) -> &BTreeMap<AccountId, ForeignAccount> {
        &self.foreign_accounts
    }

    /// Returns whether to ignore invalid input notes or not.
    pub fn ignore_invalid_input_notes(&self) -> bool {
        self.ignore_invalid_input_notes
    }

    /// Returns the auth args that the executing client passes to the auth procedure of the account.
    pub fn auth_args(&self) -> &RequestAuthArgs {
        &self.auth_args
    }

    /// Returns the expected NTX scripts that the node's NTX builder will need in its registry.
    pub fn expected_ntx_scripts(&self) -> &[NoteScript] {
        &self.expected_ntx_scripts
    }

    /// Returns the new code that the transaction gives to the executing account, if any.
    pub fn account_code_upgrade(&self) -> Option<&AccountCodeUpgrade> {
        self.account_code_upgrade.as_ref()
    }

    // STATE MUTATORS
    // --------------------------------------------------------------------------------------------

    /// Adds `note` to the notes this request consumes, without arguments. The executing client
    /// infers the authentication of the note from its store.
    ///
    /// Test harnesses use this method to add a note to a request that is already built, for example
    /// the note that pays the transaction fee. To build a request, use the
    /// [`TransactionRequestBuilder`] setters.
    ///
    /// # Errors
    /// - If the request already consumes the note.
    #[cfg(feature = "testing")]
    pub fn add_input_note(&mut self, note: Note) -> Result<(), TransactionRequestError> {
        if self.input_note_ids().any(|note_id| note_id == note.id()) {
            return Err(TransactionRequestError::DuplicateInputNote(note.id()));
        }

        self.input_notes.push(RequestInputNote {
            authentication: InputNoteAuthentication::Inferred(note),
            args: None,
        });
        Ok(())
    }

    /// Returns this request with `auth_args` as its explicit auth args.
    ///
    /// The executing party can use this method to set auth args that only it can choose, for
    /// example [`MultisigAuthArgs`](miden_standards::account::auth::MultisigAuthArgs) with a salt
    /// and a bound block of its choice. The new auth args replace the previous auth args. The
    /// client tracks the bound block of multisig auth args.
    #[must_use]
    pub fn with_auth_args<A: SequentialCommit<Commitment = Word>>(mut self, auth_args: &A) -> Self {
        self.commit_auth_args(auth_args.to_commitment(), auth_args.to_elements());
        self
    }

    /// Sets the explicit auth args to `commitment` and its `preimage`. The new auth args replace
    /// the previous auth args.
    pub fn commit_auth_args(&mut self, commitment: Word, preimage: Vec<Felt>) {
        self.auth_args = RequestAuthArgs::Explicit { commitment, preimage };
    }

    /// Builds the [`InputNotes`] needed for the transaction execution.
    ///
    /// A note with an explicit authentication keeps it. Any other note is authenticated when
    /// `authenticated_note_records` holds a record for it and unauthenticated otherwise. The result
    /// keeps the order of the request.
    pub fn build_input_notes(
        &self,
        authenticated_note_records: Vec<InputNoteRecord>,
    ) -> Result<InputNotes<InputNote>, TransactionRequestError> {
        let mut authenticated_notes: BTreeMap<NoteId, InputNoteRecord> = BTreeMap::new();
        for record in authenticated_note_records {
            // Authenticated note records always carry metadata (their inclusion proof injected it),
            // so `id()` is `Some`.
            let note_id =
                record.id().expect("authenticated note record carries metadata so id() is Some");

            if !record.is_authenticated() {
                return Err(TransactionRequestError::InputNoteNotAuthenticated(note_id));
            }
            if record.is_consumed() {
                return Err(TransactionRequestError::InputNoteAlreadyConsumed(
                    record.details_commitment(),
                ));
            }

            authenticated_notes.insert(note_id, record);
        }

        let input_notes = self
            .input_notes
            .iter()
            .map(|input_note| match &input_note.authentication {
                InputNoteAuthentication::Explicit(input_note) => input_note.clone(),
                InputNoteAuthentication::Inferred(note) => {
                    match authenticated_notes.remove(&note.id()) {
                        Some(record) => record
                            .try_into()
                            .expect("Authenticated note record should be convertible to InputNote"),
                        None => InputNote::unauthenticated(note.clone()),
                    }
                },
            })
            .collect();

        Ok(InputNotes::new(input_notes)?)
    }

    /// Converts the [`TransactionRequest`] into [`TransactionArgs`] in order to be executed by a
    /// Miden host.
    pub fn into_transaction_args(
        self,
        tx_script: Option<(TransactionScript, Word)>,
    ) -> TransactionArgs {
        let note_args: BTreeMap<NoteId, NoteArgs> = self
            .input_notes
            .iter()
            .filter_map(|input_note| input_note.args.map(|args| (input_note.id(), args)))
            .collect();
        let own_output_recipients: Vec<NoteRecipient> = self
            .expected_output_own_notes()
            .into_iter()
            .map(|note| note.recipient().clone())
            .collect();
        let TransactionRequest {
            expected_output_recipients,
            advice_map,
            merkle_store,
            account_code_upgrade,
            auth_args,
            ..
        } = self;

        let mut tx_args = TransactionArgs::new(advice_map).with_note_args(note_args);

        if let Some((tx_script, script_args)) = tx_script {
            tx_args = tx_args.with_tx_script_and_args(tx_script, script_args);
        }

        // Default auth args pass nothing. The client commits the defaults as explicit auth args
        // before it converts a request that needs them.
        if let RequestAuthArgs::Explicit { commitment, preimage } = auth_args {
            tx_args = tx_args.with_auth_args(commitment);
            tx_args.extend_advice_map([(commitment, preimage)]);
        }

        if let Some(account_code_upgrade) = account_code_upgrade {
            tx_args = tx_args.with_account_code_upgrade(account_code_upgrade);
        }

        tx_args.extend_output_note_recipients(
            own_output_recipients
                .into_iter()
                .chain(expected_output_recipients.into_values())
                .map(Box::new),
        );
        tx_args.extend_merkle_store(merkle_store.inner_nodes());

        tx_args
    }

    /// Builds the transaction script based on the account capabilities and the transaction request.
    ///
    /// Returns the script together with the `TX_SCRIPT_ARGS` word it must be executed with. A
    /// request without a [`RequestScript`] runs without a transaction script.
    ///
    /// A generated script determines its own argument. The script that creates notes reads them
    /// from the advice provider and receives only their payload commitment on the stack. The script
    /// that only expires the transaction reads the delta from its argument.
    ///
    /// Scripts supplied by the caller via [`RequestScript::Custom`] are expected to have already
    /// been compiled against the client's source manager (e.g. via `Client::code_builder`).
    pub fn build_transaction_script(
        &self,
        code_interface: &AccountCodeInterface,
    ) -> Result<Option<(TransactionScript, Word)>, TransactionRequestError> {
        match &self.transaction_script {
            Some(RequestScript::Custom { script, arg }) => {
                Ok(Some((script.clone(), arg.unwrap_or_default())))
            },
            Some(RequestScript::Generated { own_output_notes, expiration_delta }) => {
                let notes: Vec<PartialNote> =
                    own_output_notes.iter().cloned().map(Into::into).collect();
                let script = match expiration_delta {
                    Some(delta) if notes.is_empty() => {
                        let script = ExpirationTransactionScript::new(*delta);
                        (script.into(), script.tx_script_args())
                    },
                    Some(delta) => {
                        let script = SendNotesTransactionScript::with_expiration_delta(
                            code_interface,
                            &notes,
                            *delta,
                        )?;
                        (script.tx_script().clone(), script.tx_script_args())
                    },
                    None => {
                        let script = SendNotesTransactionScript::new(code_interface, &notes)?;
                        (script.tx_script().clone(), script.tx_script_args())
                    },
                };
                Ok(Some(script))
            },
            None => Ok(None),
        }
    }
}

