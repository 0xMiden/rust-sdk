pub type NoteArgs = Word;

/// Specifies a transaction script to be executed in a transaction.
///
/// A transaction script is a program which is executed after scripts of all input notes have been
/// executed.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum TransactionScriptTemplate {
    /// Specifies the exact transaction script to be executed in a transaction.
    CustomScript(TransactionScript),
    /// Specifies that the transaction script must create the specified output notes.
    ///
    /// It is up to the client to determine how the output notes will be created and this will
    /// depend on the capabilities of the account the transaction request will be applied to. For
    /// example, for Basic Wallets, this may involve invoking `create_note` procedure.
    SendNotes(Vec<PartialNote>),
}

/// Specifies a transaction request that can be executed by an account.
///
/// A request contains information about input notes to be consumed by the transaction (if any),
/// blocks that must be available to the transaction, the transaction script to execute (if any),
/// and notes expected to be generated by this transaction or a later transaction.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TransactionRequest {
    /// Blocks that the transaction must be able to authenticate against its reference block.
    block_numbers: BTreeSet<BlockNumber>,
    /// Notes to be consumed by the transaction, in consumption order.
    ///
    /// A note with an entry in `explicit_input_notes` is consumed in the mode that entry pins. The
    /// executing client infers the mode of every other note from its store.
    input_notes: Vec<Note>,
    /// Optional arguments of the input notes to be consumed by the transaction. This includes both
    /// authenticated and unauthenticated notes.
    input_notes_args: Vec<(NoteId, Option<NoteArgs>)>,
    /// Pinned consumption modes set through [`TransactionRequestBuilder::explicit_input_notes`].
    pub(super) explicit_input_notes: BTreeMap<NoteId, InputNote>,
    /// Template for the creation of the transaction script.
    script_template: Option<TransactionScriptTemplate>,
    /// A map of recipients of the output notes expected to be generated by the transaction.
    expected_output_recipients: BTreeMap<Word, NoteRecipient>,
    /// A map of details and tags of notes we expect to be created as part of future transactions
    /// with their respective tags.
    ///
    /// For example, after a swap note is consumed, a payback note is expected to be created.
    expected_future_notes: BTreeMap<NoteDetailsCommitment, (NoteDetails, NoteTag)>,
    /// Initial state of the `AdviceMap` that provides data during runtime.
    advice_map: AdviceMap,
    /// Initial state of the `MerkleStore` that provides data during runtime.
    merkle_store: MerkleStore,
    /// Foreign account data requirements keyed by account ID. At execution time, account data will
    /// be retrieved from the network, and injected as advice inputs. Additionally, the account's
    /// code will be added to the executor and prover.
    foreign_accounts: BTreeMap<AccountId, ForeignAccount>,
    /// The number of blocks in relation to the transaction's reference block after which the
    /// transaction will expire. If `None`, the transaction will not expire.
    expiration_delta: Option<u16>,
    /// Indicates whether to **silently** ignore invalid input notes when executing the transaction.
    /// This will allow the transaction to be executed even if some input notes are invalid.
    ignore_invalid_input_notes: bool,
    /// Optional [`Word`] that will be pushed to the operand stack before the transaction script
    /// execution.
    script_arg: Option<Word>,
    /// Optional [`Word`] that will be pushed to the stack for the authentication procedure during
    /// transaction execution.
    auth_arg: Option<Word>,
    /// Salt the native fee conversion info is committed under when the transaction is prepared, set
    /// through [`TransactionRequestBuilder::fee_conversion_salt`]. `None` leaves the client to use
    /// its fixed default salt.
    fee_conversion_salt: Option<Word>,
    /// Note scripts that the node's NTX builder will need in its script registry.
    ///
    /// See [`TransactionRequestBuilder::expected_ntx_scripts`] for details.
    expected_ntx_scripts: Vec<NoteScript>,
    /// New code of the executing account, set through
    /// [`TransactionRequestBuilder::account_code_upgrade`].
    account_code_upgrade: Option<AccountCodeUpgrade>,
}

impl TransactionRequest {
    // PUBLIC ACCESSORS
    // --------------------------------------------------------------------------------------------

    /// Returns the blocks that the transaction must be able to authenticate.
    pub fn block_numbers(&self) -> &BTreeSet<BlockNumber> {
        &self.block_numbers
    }

    /// Returns a reference to the transaction request's input note list.
    pub fn input_notes(&self) -> &[Note] {
        &self.input_notes
    }

    /// Returns a list of all input note IDs.
    pub fn input_note_ids(&self) -> impl Iterator<Item = NoteId> {
        self.input_notes.iter().map(Note::id)
    }

    /// Returns the assets held by the transaction's input notes.
    pub fn incoming_assets(&self) -> (BTreeMap<AccountId, u64>, Vec<Asset>) {
        collect_assets(self.input_notes.iter().flat_map(|note| note.assets().iter()))
    }

    /// Returns the arguments of the input notes, in the order of the input notes. A note without
    /// arguments has `None`.
    pub fn input_notes_args(&self) -> &[(NoteId, Option<NoteArgs>)] {
        &self.input_notes_args
    }

    /// Returns the input notes with a pinned consumption mode, keyed by note ID.
    ///
    /// Each of these notes is also in [`Self::input_notes`].
    pub fn explicit_input_notes(&self) -> &BTreeMap<NoteId, InputNote> {
        &self.explicit_input_notes
    }

    /// Returns the number of blocks after the reference block at which the transaction expires, or
    /// `None` if the transaction does not expire.
    pub fn expiration_delta(&self) -> Option<u16> {
        self.expiration_delta
    }

    /// Returns a map of note IDs to their respective [`NoteArgs`]. The result will include
    /// exclusively note IDs for notes for which [`NoteArgs`] have been defined.
    pub fn get_note_args(&self) -> BTreeMap<NoteId, NoteArgs> {
        self.input_notes_args
            .iter()
            .filter_map(|(note, args)| args.map(|a| (*note, a)))
            .collect()
    }

    /// Returns the expected output own notes of the transaction.
    ///
    /// In this context "own notes" refers to notes that are expected to be created directly by the
    /// transaction script, rather than notes that are created as a result of consuming other notes.
    pub fn expected_output_own_notes(&self) -> Vec<Note> {
        match &self.script_template {
            Some(TransactionScriptTemplate::SendNotes(notes)) => notes
                .iter()
                .map(|partial| {
                    Note::with_attachments(
                        partial.assets().clone(),
                        *partial.partial_metadata(),
                        self.expected_output_recipients
                            .get(&partial.recipient_digest())
                            .expect("Recipient should be included if it's an own note")
                            .clone(),
                        partial.attachments().clone(),
                    )
                })
                .collect(),
            _ => vec![],
        }
    }

    /// Returns an iterator over the expected output notes.
    pub fn expected_output_recipients(&self) -> impl Iterator<Item = &NoteRecipient> {
        self.expected_output_recipients.values()
    }

    /// Returns an iterator over expected future notes.
    pub fn expected_future_notes(&self) -> impl Iterator<Item = &(NoteDetails, NoteTag)> {
        self.expected_future_notes.values()
    }

    /// Returns the [`TransactionScriptTemplate`].
    pub fn script_template(&self) -> &Option<TransactionScriptTemplate> {
        &self.script_template
    }

    /// Returns the [`AdviceMap`] for the transaction request.
    pub fn advice_map(&self) -> &AdviceMap {
        &self.advice_map
    }

    /// Returns a mutable reference to the [`AdviceMap`] for the transaction request.
    pub fn advice_map_mut(&mut self) -> &mut AdviceMap {
        &mut self.advice_map
    }

    /// Returns the [`MerkleStore`] for the transaction request.
    pub fn merkle_store(&self) -> &MerkleStore {
        &self.merkle_store
    }

    /// Returns the required foreign accounts keyed by account ID.
    pub fn foreign_accounts(&self) -> &BTreeMap<AccountId, ForeignAccount> {
        &self.foreign_accounts
    }

    /// Returns whether to ignore invalid input notes or not.
    pub fn ignore_invalid_input_notes(&self) -> bool {
        self.ignore_invalid_input_notes
    }

    /// Returns the script argument for the transaction request.
    pub fn script_arg(&self) -> &Option<Word> {
        &self.script_arg
    }

    /// Returns the auth argument for the transaction request.
    pub fn auth_arg(&self) -> &Option<Word> {
        &self.auth_arg
    }

    /// Returns the caller-declared salt for the native fee conversion info the client commits when
    /// preparing the transaction, set through [`TransactionRequestBuilder::fee_conversion_salt`].
    pub fn fee_conversion_salt(&self) -> Option<Word> {
        self.fee_conversion_salt
    }

    /// Returns whether the request carries an auth arg that commits anything.
    ///
    /// An empty word counts as no arg: otherwise it would suppress the conversion info the client
    /// attaches, leaving `fee::pay_fee` nothing to read.
    pub fn has_auth_arg(&self) -> bool {
        self.auth_arg.is_some_and(|auth_arg| auth_arg != Word::empty())
    }

    /// Returns the expected NTX scripts that the node's NTX builder will need in its registry.
    pub fn expected_ntx_scripts(&self) -> &[NoteScript] {
        &self.expected_ntx_scripts
    }

    /// Returns the new code that the transaction gives to the executing account, if any.
    pub fn account_code_upgrade(&self) -> Option<&AccountCodeUpgrade> {
        self.account_code_upgrade.as_ref()
    }

    // STATE MUTATORS
    // --------------------------------------------------------------------------------------------

    /// Adds `note` to the notes this request consumes, as an unauthenticated input.
    ///
    /// Building a request that consumes the note is the public way to do this. The harness needs it
    /// on a request a test already built.
    #[cfg(feature = "testing")]
    pub fn add_unauthenticated_input_note(&mut self, note: Note) {
        self.input_notes_args.push((note.id(), None));
        self.input_notes.push(note);
    }

    /// Returns this request with the auth arg set to the commitment of `auth_args`, and with their
    /// preimage added to the advice map.
    ///
    /// The executing party can use this method to set auth args that only it can choose, for
    /// example [`MultisigAuthArgs`](miden_standards::account::auth::MultisigAuthArgs) with a salt
    /// and a bound block of its choice. The new auth args replace the previous auth args and the
    /// declared fee conversion salt. The client tracks the bound block of multisig auth args.
    #[must_use]
    pub fn with_auth_args<A: SequentialCommit<Commitment = Word>>(mut self, auth_args: &A) -> Self {
        self.commit_auth_args(auth_args.to_commitment(), auth_args.to_elements());
        self.fee_conversion_salt = None;
        self
    }

    /// Sets `auth_arg` and adds its `preimage` to the advice map.
    pub fn commit_auth_args(&mut self, auth_arg: Word, preimage: Vec<Felt>) {
        self.advice_map.insert(auth_arg, preimage);
        self.auth_arg = Some(auth_arg);
    }

    /// Checks the invariants every request must hold, whether it was built or deserialized.
    ///
    /// # Errors
    /// - If a note appears more than once among the input notes.
    fn validate(&self) -> Result<(), TransactionRequestError> {
        let mut seen_input_notes = BTreeSet::new();
        for (note_id, _) in &self.input_notes_args {
            if !seen_input_notes.insert(note_id) {
                return Err(TransactionRequestError::DuplicateInputNote(*note_id));
            }
        }

        Ok(())
    }

    /// Builds the [`InputNotes`] needed for the transaction execution.
    ///
    /// A note with a pinned mode keeps that mode. Any other note is authenticated when
    /// `authenticated_note_records` holds a record for it and unauthenticated otherwise. The result
    /// keeps the order of the request.
    pub fn build_input_notes(
        &self,
        authenticated_note_records: Vec<InputNoteRecord>,
    ) -> Result<InputNotes<InputNote>, TransactionRequestError> {
        let mut authenticated_notes: BTreeMap<NoteId, InputNoteRecord> = BTreeMap::new();
        for record in authenticated_note_records {
            // Authenticated note records always carry metadata (their inclusion proof injected it),
            // so `id()` is `Some`.
            let note_id =
                record.id().expect("authenticated note record carries metadata so id() is Some");

            if !record.is_authenticated() {
                return Err(TransactionRequestError::InputNoteNotAuthenticated(note_id));
            }
            if record.is_consumed() {
                return Err(TransactionRequestError::InputNoteAlreadyConsumed(
                    record.details_commitment(),
                ));
            }

            authenticated_notes.insert(note_id, record);
        }

        let input_notes = self
            .input_notes()
            .iter()
            .map(|note| match self.explicit_input_notes.get(&note.id()) {
                Some(input_note) => input_note.clone(),
                None => match authenticated_notes.remove(&note.id()) {
                    Some(record) => record
                        .try_into()
                        .expect("Authenticated note record should be convertible to InputNote"),
                    None => InputNote::unauthenticated(note.clone()),
                },
            })
            .collect();

        Ok(InputNotes::new(input_notes)?)
    }

    /// Converts the [`TransactionRequest`] into [`TransactionArgs`] in order to be executed by a
    /// Miden host.
    pub fn into_transaction_args(
        self,
        tx_script: Option<(TransactionScript, Option<Word>)>,
    ) -> TransactionArgs {
        let note_args = self.get_note_args();
        let TransactionRequest {
            expected_output_recipients,
            advice_map,
            merkle_store,
            account_code_upgrade,
            ..
        } = self;

        let mut tx_args = TransactionArgs::new(advice_map).with_note_args(note_args);

        // A script argument without a script has nothing to bind to, so it is only applied when a
        // transaction script is present. With no argument the default empty word is used, which is
        // equivalent to setting no argument at all.
        if let Some((tx_script, script_args)) = tx_script {
            let script_args = script_args.or(self.script_arg).unwrap_or_default();
            tx_args = tx_args.with_tx_script_and_args(tx_script, script_args);
        }

        if let Some(auth_argument) = self.auth_arg {
            tx_args = tx_args.with_auth_args(auth_argument);
        }

        if let Some(account_code_upgrade) = account_code_upgrade {
            tx_args = tx_args.with_account_code_upgrade(account_code_upgrade);
        }

        tx_args
            .extend_output_note_recipients(expected_output_recipients.into_values().map(Box::new));
        tx_args.extend_merkle_store(merkle_store.inner_nodes());

        tx_args
    }

    /// Builds the transaction script based on the account capabilities and the transaction request.
    ///
    /// Returns the script together with the `TX_SCRIPT_ARGS` word it must be executed with, if the
    /// script determines it. The `SendNotes` script reads the notes it creates from the advice
    /// provider and only receives their payload commitment on the stack, so its argument is fixed
    /// by the notes the script was built for, and passing anything else makes the script fail to
    /// resolve its payload. A caller-supplied [`TransactionScriptTemplate::CustomScript`] carries
    /// no such constraint and yields `None`, so the request's own
    /// [`TransactionRequestBuilder::script_arg`] applies to it.
    ///
    /// A request without a script template normally runs without a transaction script. When such a
    /// request sets an expiration delta, the standard [`ExpirationTransactionScript`] is used so
    /// that the delta is enforced; the script reads the delta from its own `TX_SCRIPT_ARGS`.
    ///
    /// Scripts supplied by the caller via [`TransactionScriptTemplate::CustomScript`] are expected
    /// to have already been compiled against the client's source manager (e.g. via
    /// `Client::code_builder`).
    pub fn build_transaction_script(
        &self,
        code_interface: &AccountCodeInterface,
    ) -> Result<Option<(TransactionScript, Option<Word>)>, TransactionRequestError> {
        match &self.script_template {
            Some(TransactionScriptTemplate::CustomScript(script)) => {
                Ok(Some((script.clone(), None)))
            },
            Some(TransactionScriptTemplate::SendNotes(notes)) => {
                let script = match self.expiration_delta.and_then(NonZeroU16::new) {
                    Some(delta) => SendNotesTransactionScript::with_expiration_delta(
                        code_interface,
                        notes,
                        delta,
                    )?,
                    None => SendNotesTransactionScript::new(code_interface, notes)?,
                };
                Ok(Some((script.tx_script().clone(), Some(script.tx_script_args()))))
            },
            None => match self.expiration_delta.and_then(NonZeroU16::new) {
                Some(delta) => {
                    let script = ExpirationTransactionScript::new(delta);
                    Ok(Some((script.into(), Some(script.tx_script_args()))))
                },
                None => Ok(None),
            },
        }
    }
}

